  const ATTRIBUTES = ["aria-label", "placeholder", "title"];

  function wrapWhitespace(original, translated) {
    const leading = original.match(/^\s*/)?.[0] || "";
    const trailing = original.match(/\s*$/)?.[0] || "";
    return `${leading}${translated}${trailing}`;
  }

  function translateString(value) {
    if (typeof value !== "string") {
      return value;
    }
    const trimmed = value.trim();
    if (!trimmed || !/[A-Za-z]/.test(trimmed)) {
      return value;
    }
    if (EXACT_TRANSLATIONS.has(trimmed)) {
      return wrapWhitespace(value, EXACT_TRANSLATIONS.get(trimmed));
    }
    for (const [pattern, replacer] of PATTERN_TRANSLATIONS) {
      if (pattern.test(trimmed)) {
        return wrapWhitespace(value, trimmed.replace(pattern, replacer));
      }
    }
    let inlineTranslated = trimmed;
    for (const [pattern, replacement] of INLINE_REPLACEMENTS) {
      inlineTranslated = inlineTranslated.replace(pattern, replacement);
    }
    if (inlineTranslated !== trimmed) {
      return wrapWhitespace(value, inlineTranslated);
    }
    return value;
  }

  function translateElementAttributes(element) {
    for (const attributeName of ATTRIBUTES) {
      if (!element.hasAttribute(attributeName)) {
        continue;
      }
      const currentValue = element.getAttribute(attributeName);
      const nextValue = translateString(currentValue);
      if (nextValue !== currentValue) {
        element.setAttribute(attributeName, nextValue);
      }
    }
  }

  function shouldSkipNode(node) {
    const parent = node.parentElement;
    if (!parent) {
      return false;
    }
    return ["SCRIPT", "STYLE", "NOSCRIPT", "TEXTAREA"].includes(parent.tagName);
  }

  function translateTextNode(node) {
    if (shouldSkipNode(node)) {
      return;
    }
    const nextValue = translateString(node.nodeValue || "");
    if (nextValue !== node.nodeValue) {
      node.nodeValue = nextValue;
    }
  }

  function translateTree(root) {
    if (!root) {
      return;
    }
    if (root.nodeType === Node.TEXT_NODE) {
      translateTextNode(root);
      return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE) {
      return;
    }
    translateElementAttributes(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    let current = walker.currentNode;
    while (current) {
      if (current.nodeType === Node.TEXT_NODE) {
        translateTextNode(current);
      } else if (current.nodeType === Node.ELEMENT_NODE) {
        translateElementAttributes(current);
      }
      current = walker.nextNode();
    }
  }

  function translateDocument() {
    document.documentElement.lang = "zh-CN";
    document.title = translateString(document.title);
    translateTree(document.body);
  }

  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === "characterData") {
        translateTextNode(mutation.target);
        continue;
      }
      mutation.addedNodes.forEach((node) => translateTree(node));
      if (mutation.type === "attributes" && mutation.target instanceof Element) {
        translateElementAttributes(mutation.target);
      }
    }
  });

  document.addEventListener("DOMContentLoaded", () => {
    translateDocument();
    if (document.body) {
      observer.observe(document.body, {
        subtree: true,
        childList: true,
        characterData: true,
        attributes: true,
        attributeFilter: ATTRIBUTES
      });
    }
  });
